#!/usr/bin/env python3
"""商品の実寸から「体との大きさ」の行に書く文と比の数を出す（どの絵でも同じ大きさに描かせ、測った比と比べる元の数）。

使い方:
  python3 scripts/体との比.py <縦cm> <横cm> <女性|男性> [商品の呼び名]
  例: python3 scripts/体との比.py 14.5 13 女性 輪

出す物（標準出力。そのまま 店の設計.md の「0 商品の形」の「体との大きさ」の行の2列目に貼る）:
  「<呼び名>の縦 14.5cm は、女性の 手の長さの 0.85・手の幅の 1.93・肩の幅の 0.38・頭の縦の 0.66・腰の幅の 0.48。
    横 13cm は、手の長さの 0.76・…」
体の物差し（日本人の大人の目安。絵の比を出すためだけの数）は、この道具の 物差し が正本。写真の指示文.md の表は同じ数の写し。

終了コード: 0 出した ／ 2 引数が違う（数でない・0以下・性別が 女性／男性 でない）
"""
import sys

物差し = {
    "女性": {"手の長さ": 17.0, "手の幅": 7.5, "肩の幅": 38.0, "頭の縦": 22.0, "腰の幅": 30.0},
    "男性": {"手の長さ": 19.0, "手の幅": 8.5, "肩の幅": 43.0, "頭の縦": 23.0, "腰の幅": 32.0},
}


def 比たち(cm, 性):
    return {k: round(cm / v, 2) for k, v in 物差し[性].items()}


def main(a):
    try:
        縦, 横 = float(a[1]), float(a[2]); 性 = a[3]; 名 = a[4] if len(a) > 4 else "商品"
        if 縦 <= 0 or 横 <= 0 or 性 not in 物差し: raise ValueError
    except Exception:
        print(__doc__, file=sys.stderr); return 2
    def 文(辺, cm):
        return f"{辺} {cm:g}cm は、" + "・".join(f"{k}の {v:.2f}" for k, v in 比たち(cm, 性).items())
    print(f"{名}の{文('縦', 縦)}（{性}の体で）。{文('横', 横)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
